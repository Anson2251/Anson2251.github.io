import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { apps } from "../src/data/apps.ts";

/**
 * Regenerate the dev-host sitemap from the landing page's app list.
 *
 * Evaluates `src/data/apps.ts` directly (Node strips types natively, no
 * build step), keeps same-host (dev.ansonate.ink) URLs, and writes
 * `docs/sitemap.xml`, which GitHub Pages serves at
 * https://dev.ansonate.ink/sitemap.xml.
 *
 * A sitemap may only list URLs on its own host, so apps hosted elsewhere
 * are skipped with a warning. The apex dev.ansonate.ink/ is excluded on
 * purpose: it is a noindex redirect to https://ansonate.ink/apps, and
 * sitemaps should only contain indexable canonical URLs.
 *
 * Usage:
 *   node scripts/sync-dev-sitemap.mjs          # write docs/sitemap.xml
 *   node scripts/sync-dev-sitemap.mjs --check  # exit 1 if docs/sitemap.xml is stale
 */

const DEV_ORIGIN = "https://dev.ansonate.ink";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.resolve(root, "../docs/sitemap.xml");

function readAppUrls() {
	const urls = [];
	for (const app of apps) {
		if (typeof app?.url !== "string") continue;
		const url = app.url.trim();
		if (url === DEV_ORIGIN || url === `${DEV_ORIGIN}/`) continue; // apex redirect, not indexable
		if (!url.startsWith(`${DEV_ORIGIN}/`)) {
			console.warn(`[sync-dev-sitemap] Skipping non-dev-host URL: ${url}`);
			continue;
		}
		urls.push(url.endsWith("/") ? url : `${url}/`);
	}
	const unique = [...new Set(urls)].sort();
	if (unique.length === 0) {
		console.error("[sync-dev-sitemap] No dev.ansonate.ink app URLs found, refusing to write an empty sitemap.");
		process.exit(1);
	}
	return unique;
}

function escapeXml(value) {
	return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function buildSitemap(urls) {
	const entries = urls.map((loc) => `  <url>\n    <loc>${escapeXml(loc)}</loc>\n  </url>`).join("\n");
	return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by landing/scripts/sync-dev-sitemap.mjs from src/data/apps.ts — do not edit by hand. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`;
}

const urls = readAppUrls();
const xml = buildSitemap(urls);

if (process.argv.includes("--check")) {
	const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : null;
	if (current === xml) {
		console.log(`[sync-dev-sitemap] OK: ${path.relative(root, outFile)} is in sync (${urls.length} urls).`);
	} else {
		console.error(`[sync-dev-sitemap] STALE: ${path.relative(root, outFile)} is out of sync. Run: node scripts/sync-dev-sitemap.mjs`);
		process.exit(1);
	}
} else {
	const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : null;
	if (current === xml) {
		console.log(`[sync-dev-sitemap] No changes (${urls.length} urls).`);
	} else {
		fs.writeFileSync(outFile, xml);
		console.log(`[sync-dev-sitemap] Wrote ${urls.length} urls to ${path.relative(root, outFile)}`);
	}
}
